    // Końcowy znak oryginału (? ! …) przechodzi na tłumaczenie — lektor czyta pytanie jak pytanie.
    function duoPhraseEnd(pl, src) {
        if (/[.!?…]$/.test(pl)) return pl;
        const m = String(src).match(/([.!?…]+)[\s"'”’»)]*$/);
        return m ? pl + m[1] : pl;
    }
    // [AGENT-EXP] Słownik ma angielskie klucze: kwestia z jawnie podanym INNYM językiem (de, es, zh-CN…) idzie dalej
    // bez sprawdzania. Brak języka, „auto” albo „und” = sprawdzamy (jak w Piperze).
    function duoPhraseLangOk(lang) {
        const l = String(lang || '').toLowerCase().trim();
        if (!l || l === 'auto' || l === 'und') return true;
        if (!/^[a-z]{2,3}(?:[-_][a-z0-9-]+)?$/.test(l)) return true;
        return l.slice(0, 2) === 'en';
    }
    // Zwraca gotowe tłumaczenie albo '' (brak w słowniku → dalej pamięć / lokalny / sieć).
    function duoPhraseLookup(text, lang) {
        try {
            if (!duoPhraseLangOk(lang)) return '';   // [AGENT-EXP]
            const raw = String(text || '').replace(/<[^>]*>/g, ' ').replace(/\[[^\]]*\]/g, ' ').trim();   // <i>…</i>, [wzdycha]
            if (!raw || raw.length > 200) return '';
            const whole = DUO_PHRASE_MAP.get(duoPhraseKey(raw));
            if (whole) return duoPhraseEnd(whole, raw);
            // kilka krótkich zdań w jednej kwestii — tylko gdy KAŻDE jest w słowniku
            const parts = raw.match(/[^.!?…]+(?:[.!?…]+|$)/g) || [];
            if (parts.length < 2) return '';
            const out = [];
            for (const p of parts) {
                const pl = DUO_PHRASE_MAP.get(duoPhraseKey(p));
                if (!pl) return '';
                out.push(duoPhraseEnd(pl, p));
            }
            return out.join(' ');
        } catch (e) { return ''; }
    }
